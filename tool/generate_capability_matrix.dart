/// Escapes a selector for use inside a markdown table cell.
///
/// A literal `|` (as in `svg|rect` or `[attr|="v"]`) would otherwise be read
/// as a column separator and break the table.
String cell(String css) => '`${css.replaceAll('|', r'\|')}`';

String describe(String css) {
  final Sel sel;
  try {
    sel = css.contains('::') ? parseWithPseudoElements(css) : parse(css);
  } on FormatException {
    return '| ${cell(css)} | ❌ not supported | rejected at parse time |';
  }
  final needs = sel.undecidableParts.map((n) => n.replaceAll('|', r'\|'));
  return switch (sel.support) {
    MatchSupport.decidable =>
      '| ${cell(css)} | ✅ full | matches against the DOM |',
    MatchSupport.requiresContext =>
      '| ${cell(css)} | ⚙️ needs context | supply ${needs.join(", ")} via `MatchContext` |',
    MatchSupport.neverDecidable =>
      '| ${cell(css)} | ⬜ parse only | represents a rendered fragment; never matches a node |',
  };
}

String buildMatrix() {
  final out = StringBuffer()
    ..writeln(startMarker)
    ..writeln()
    ..writeln('<!-- Generated by tool/generate_capability_matrix.dart.')
    ..writeln('     Do not edit by hand; run the tool to refresh. -->')
    ..writeln()
    ..writeln('| Support | Meaning |')
    ..writeln('| --- | --- |')
    ..writeln('| ✅ full | Decided from the DOM alone. |')
    ..writeln('| ⚙️ needs context | Correct once you pass the required '
        'runtime state in a `MatchContext`; without it, treated as a '
        'non-match (or throws under `strict: true`). |')
    ..writeln('| ⬜ parse only | Parses and serializes, but denotes a '
        'rendered fragment rather than an element, so it never matches. |')
    ..writeln();

  var full = 0;
  var ctx = 0;
  var parseOnly = 0;
  for (final entry in groups.entries) {
    out
      ..writeln('#### ${entry.key}')
      ..writeln()
      ..writeln('| Selector | Support | Notes |')
      ..writeln('| --- | --- | --- |');
    for (final css in entry.value) {
      final row = describe(css);
      if (row.contains('✅')) {
        full++;
      } else if (row.contains('⚙️')) {
        ctx++;
      } else {
        parseOnly++;
      }
      out.writeln(row);
    }
    out.writeln();
  }
  out
    ..writeln('**Totals:** $full fully supported · $ctx context-dependent · '
        '$parseOnly parse-only.')
    ..writeln()
    ..writeln(endMarker);
  return out.toString().trimRight();
}

void main(List<String> args) {
  final check = args.contains('--check');
  final readme = File('README.md');
  if (!readme.existsSync()) {
    stderr.writeln('README.md not found; run from the package root.');
    exit(2);
  }

  final content = readme.readAsStringSync();
  final start = content.indexOf(startMarker);
  final end = content.indexOf(endMarker);
  if (start < 0 || end < 0) {
    stderr.writeln('Markers not found in README.md. Add:\n'
        '$startMarker\n$endMarker');
    exit(2);
  }

  final updated =
      content.replaceRange(start, end + endMarker.length, buildMatrix());

  if (check) {
    if (updated != content) {
      stderr.writeln('README.md capability matrix is stale. '
          'Run: dart run tool/generate_capability_matrix.dart');
      exit(1);
    }
    print('Capability matrix is up to date.');
    return;
  }

  readme.writeAsStringSync(updated);
  print('Updated the capability matrix in README.md.');
}
