// Generates the selector capability matrix in README.md from the code itself.
//
// The old README carried a hand-written "Limitations" paragraph that drifted
// from reality — it listed selectors as unsupported that were, and omitted
// ones that were broken. This derives the table from MatchSupport, so the
// documentation cannot disagree with the implementation.
//
// Usage:
//   dart run tool/generate_capability_matrix.dart          # rewrite README
//   dart run tool/generate_capability_matrix.dart --check   # CI: verify only
